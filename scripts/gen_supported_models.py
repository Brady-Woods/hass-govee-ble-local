"""Generate the README's table of supported models from the installed govee-ble-local.

The library decides which models the integration supports (``supported_skus()``), so the README's
list is generated from it, not kept by hand. Run it against the manifest's floor library, the
version every user is guaranteed to have (a newer one can only add models):

    python scripts/gen_supported_models.py           # rewrite the block in README.md
    python scripts/gen_supported_models.py --check   # exit 1 if README.md is out of date

Only the library's public API is used. "Tested" marks the models in this repository's real-hardware
test set (TESTED below), not a library support level.
"""

from __future__ import annotations

import argparse
from importlib.metadata import version
from pathlib import Path
import sys

from govee_ble_local import DeviceProfile, profile_for, supported_skus

README = Path(__file__).resolve().parent.parent / "README.md"
BEGIN = "<!-- BEGIN supported-models: generated by scripts/gen_supported_models.py, do not edit -->"
END = "<!-- END supported-models -->"

# The real-hardware test set: models checked with this integration on real devices.
TESTED = frozenset({"H5083", "H6006", "H6008", "H6047", "H6052", "H60A6", "H61A8", "H6641"})

# The pacts asked about for a model the library serves only at the pact it advertises (it has no
# profile without one): every (pact_type, pact_code) up to 255 each, past any the library routes.
# The library has no public list of a model's pacts; asking at each takes well under a second.
PROBED_PACTS = tuple((pact_type, code) for pact_type in range(256) for code in range(256))


def _pacts(pacts: list[tuple[int, int]]) -> str:
    """Return ``pacts`` as the README names them: "2,1", "10,1 or 10,2"."""
    names = [f"{pact_type},{code}" for pact_type, code in pacts]
    return names[0] if len(names) == 1 else f"{', '.join(names[:-1])} or {names[-1]}"


def _features(sku: str) -> tuple[str, str, bool]:
    """Return the model's type, its features, and whether it needs its advertised pact.

    A model the library serves only at its rows' pacts has no profile without one: its
    features are those of the profiles at the pacts it is served at, which the row names.
    """
    if (profile := profile_for(sku, allow_modelled=True)) is not None:
        return *_describe(profile), False
    served: dict[tuple[str, str], list[tuple[int, int]]] = {}
    for pact in PROBED_PACTS:
        if (profile := profile_for(sku, pact=pact, allow_modelled=True)) is not None:
            served.setdefault(_describe(profile), []).append(pact)
    if not served:  # supported_skus() lists only SKUs with a profile at some pact
        raise ValueError(f"{sku}: listed as supported but has no profile at any probed pact")
    kinds = sorted({kind for kind, _ in served})
    if len(served) == 1:
        [((_, features), pacts)] = served.items()
        return kinds[0], f"{features}; only at protocol {_pacts(pacts)}", True
    features = "; ".join(
        f"at protocol {_pacts(pacts)}: {features}" for (_, features), pacts in served.items()
    )
    return " / ".join(kinds), features, True


def _describe(profile: DeviceProfile) -> tuple[str, str]:
    """Return the type and the features of a library profile."""
    caps = {str(cap.value) for cap in profile.capabilities}
    if profile.relay:
        kind = "Smart plug"
        features = ["on/off"]
        if profile.requires_secret:
            features.append("needs its secret key")
        return kind, ", ".join(features)
    kind = "Light"
    features = [
        label
        for cap, label in (
            ("power", "on/off"),
            ("brightness", "brightness"),
            ("rgb", "RGB"),
        )
        if cap in caps
    ]
    if "color_temp" in caps:
        if profile.min_kelvin and profile.max_kelvin:
            overrides = [
                *(
                    f"{low}-{high} K from hardware {v}"
                    for v, low, high in profile.kelvin_by_hardware
                ),
                *(
                    f"{low}-{high} K from software {v}"
                    for v, low, high in profile.kelvin_by_software
                ),
                *(
                    f"{low}-{high} K on protocol {pact[0]},{pact[1]}"
                    for pact, low, high in profile.kelvin_by_pact
                ),
            ]
            note = f" ({'; '.join(overrides)})" if overrides else ""
            features.append(f"colour temp {profile.min_kelvin}-{profile.max_kelvin} K{note}")
        else:
            features.append("colour temp")
    if "scenes" in caps:
        features.append("scenes")
    if profile.zones:
        features.append(f"{len(profile.zones)} zones ({', '.join(z.name for z in profile.zones)})")
    if "segments" in caps and profile.segments:
        features.append(f"up to {profile.segments} segments")
    return kind, ", ".join(features)


def render() -> str:
    """Return the README block for the installed library, markers included."""
    default = set(supported_skus())
    every = supported_skus(allow_modelled=True)
    opt_in = [sku for sku in every if sku not in default]
    rows = []
    pact_only = False
    for sku in every:
        kind, features, needs_pact = _features(sku)
        pact_only |= needs_pact
        if sku in TESTED:
            status = "✅ Tested"
        elif sku in default:
            status = "Supported"
        else:
            status = "Opt-in"
        rows.append((kind != "Light", sku, kind, features, status))
    rows.sort()
    lines = [
        BEGIN,
        f"With `govee-ble-local` {version('govee-ble-local')}, the integration supports"
        f" **{len(default)} models**, plus **{len(opt_in)}** more you can opt in to"
        f" ({', '.join(opt_in)}). A newer library version can add models.",
        "",
        "- **✅ Tested:** in the real-hardware test set above.",
        "- **Supported:** set up like any other model; its support comes from the Govee app's own"
        " code, and it hasn't been tested on a real device here.",
        "- **Opt-in:** support is inferred, not traced in the app; setting one up asks you first.",
        "",
        "A colour-temperature range is the model's base range; where the range in use depends on"
        " the light's hardware or software version, or on the protocol it advertises, its row"
        " says so.",
        "",
    ]
    if pact_only:
        lines += [
            "A model supported only at some protocol versions is set up once Home Assistant has"
            " heard the light advertise one of them; its row names them.",
            "",
        ]
    lines += [
        "<details>",
        f"<summary>All {len(every)} models</summary>",
        "",
        "| Model | Type | Features | Status |",
        "| --- | --- | --- | --- |",
    ]
    lines += [
        f"| {sku} | {kind} | {features} | {status} |" for _, sku, kind, features, status in rows
    ]
    lines += ["", "</details>", END]
    return "\n".join(lines)


def block_in(text: str) -> str:
    """Return the generated block in ``text``, markers included."""
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        raise ValueError(f"{README.name}: the supported-models markers are missing")
    return text[start : end + len(END)]


def main() -> int:
    """Rewrite README.md's block, or with --check report whether it is up to date."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if README.md is out of date")
    args = parser.parse_args()
    text = README.read_text(encoding="utf-8")
    current, fresh = block_in(text), render()
    if args.check:
        if current != fresh:
            print(
                f"{README.name} is out of date: run scripts/gen_supported_models.py",
                file=sys.stderr,
            )
            return 1
        return 0
    README.write_text(text.replace(current, fresh), encoding="utf-8")
    print(f"{README.name}: supported-models block updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
